-- 通貨ごとの毎月の支出上限と、キャラごとの推し開始日。

create table public.spending_budget (
  spending_budget_id bigint generated by default as identity primary key,
  members_id uuid not null references auth.users (id) on delete cascade,
  currency_code text not null,
  monthly_amount integer not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint spending_budget_amount_check
    check (monthly_amount >= 0 and monthly_amount <= 999999999),
  constraint spending_budget_currency_len_check
    check (char_length(currency_code) >= 3 and char_length(currency_code) <= 8),
  constraint spending_budget_members_currency_key
    unique (members_id, currency_code)
);

comment on table public.spending_budget is
  '通貨ごとの毎月の支出上限。月ごとに金額は変えない。換算しない';
comment on column public.spending_budget.currency_code is
  '記録通貨。別通貨とは足さない';
comment on column public.spending_budget.monthly_amount is
  '毎月の上限。0以上';

alter table public.spending_budget enable row level security;

create policy spending_budget_self_all
  on public.spending_budget
  for all
  to authenticated
  using ( (select auth.uid()) = members_id )
  with check ( (select auth.uid()) = members_id );

create policy spending_budget_reject_anonymous
  on public.spending_budget
  as restrictive
  for all
  to authenticated
  using ( public.jwt_is_permanent_user() )
  with check ( public.jwt_is_permanent_user() );

create index spending_budget_members_id_idx
  on public.spending_budget (members_id);

grant select, insert, update, delete on table public.spending_budget to authenticated;
grant all on table public.spending_budget to service_role;
revoke all on table public.spending_budget from anon;

grant usage, select on sequence public.spending_budget_spending_budget_id_seq
  to authenticated;
grant all on sequence public.spending_budget_spending_budget_id_seq
  to service_role;

create table public.oshi_day (
  oshi_day_id bigint generated by default as identity primary key,
  members_id uuid not null references auth.users (id) on delete cascade,
  character_name text not null,
  start_date date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint oshi_day_character_name_len_check
    check (char_length(character_name) >= 1 and char_length(character_name) <= 80),
  constraint oshi_day_members_character_key
    unique (members_id, character_name)
);

comment on table public.oshi_day is
  'キャラクターごとの推し開始日。その日を1日目として数える';
comment on column public.oshi_day.character_name is
  '登録製品のキャラクター名と揃える表示名';
comment on column public.oshi_day.start_date is
  '推し始めた日。この日が1日目';

